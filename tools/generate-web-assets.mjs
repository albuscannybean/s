import {readdir,readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import path from 'node:path';
import {APP_VERSION} from '../packages/app-metadata.js';
import './stage-pdfjs.mjs';
import './verify-course-publication.mjs';
const base=new URL('../',import.meta.url);
// Discover native ESM dependencies once at build time to remove the cold-start waterfall.
const modules=new Set();
async function dependencies(file){
 if(modules.has(file))return;modules.add(file);
 const source=await readFile(new URL(file,base),'utf8');
 for(const match of source.matchAll(/(?:from\s*|import\s*)['"]([^'"]+)['"]/g)){
  if(!match[1].startsWith('.'))continue;
  const target=path.posix.normalize(path.posix.join(path.posix.dirname(file),match[1]));
  if(target.endsWith('.js'))await dependencies(target);
 }
}
await dependencies('apps/web/app.js');
const htmlUrl=new URL('apps/web/index.html',base),original=await readFile(htmlUrl,'utf8');
const preload='<!-- modulepreload:start -->\n'+[...modules].filter(p=>p!=='apps/web/app.js').sort().map(p=>'<link rel="modulepreload" href="'+(p.startsWith('apps/web/')?'./'+p.slice(9):'../../'+p)+'">').join('\n')+'\n<!-- modulepreload:end -->';
await writeFile(htmlUrl,original.includes('<!-- modulepreload:start -->')?original.replace(/<!-- modulepreload:start -->[\s\S]*?<!-- modulepreload:end -->/,preload):original.replace('</head>',preload+'\n</head>'));
async function walk(relative){const entries=await readdir(new URL(relative,base),{withFileTypes:true}),files=[];for(const entry of entries){const p=relative+entry.name;if(entry.isDirectory())files.push(...await walk(p+'/'));else files.push(p)}return files}
const packages=(await walk('packages/')).filter(p=>/\.(js|css)$/.test(p));
const appFiles=(await walk('apps/web/')).filter(p=>!p.endsWith('/sw.js')&&(
 /\.(js|mjs|html|css|woff2|webmanifest|bcmap|wasm|icc|ttf|pfb|otf)$/.test(p)
 ||p.startsWith('apps/web/course-text/')&&/\.json(?:\.gz)?$/.test(p)
));
const assets=[...appFiles,...packages].sort(),hash=createHash('sha256');
const assetPath=file=>file.startsWith('apps/web/')?'./'+file.slice(9):'../../'+file;
const checksums={};
for(const file of assets){
 const content=await readFile(new URL(file,base));
 hash.update(file);hash.update(content);
 checksums[assetPath(file)]=createHash('sha256').update(content).digest('hex');
}
checksums['./']=checksums['./index.html'];
hash.update(await readFile(new URL('tools/generate-web-assets.mjs',base)));
const paths=['./',...assets.map(assetPath)];
const worker=String.raw`// Generated by tools/generate-web-assets.mjs. Do not maintain parallel asset lists.
const REVISION='lmn-v${APP_VERSION}-web-${hash.digest('hex').slice(0,12)}';
const CACHE_PREFIX='lmn-web:'+self.registration.scope+':';
const CACHE=CACHE_PREFIX+REVISION;
const ASSETS=${JSON.stringify(paths,null,2)};
const CHECKSUMS=${JSON.stringify(checksums)};
const ROOT=new URL('./',self.location.href);
const PACKAGES=new URL('../../packages/',ROOT);
const ASSET_URLS=new Map(ASSETS.map(asset=>{
 const url=new URL(asset,ROOT);
 return [url.pathname,asset==='./index.html'?ROOT.href:url.href];
}));
const EXPECTED=new Map(ASSETS.map(asset=>[
 asset==='./index.html'?ROOT.href:new URL(asset,ROOT).href,CHECKSUMS[asset]
]));

async function verified(response,key){
 if(!response?.ok||response.redirected)return false;
 const digest=await crypto.subtle.digest('SHA-256',await response.clone().arrayBuffer());
 return Array.from(new Uint8Array(digest),byte=>byte.toString(16).padStart(2,'0')).join('')===EXPECTED.get(key);
}

self.addEventListener('install',event=>event.waitUntil((async()=>{
 const assets=await Promise.all([...new Set(ASSET_URLS.values())].map(async key=>{
  const response=await fetch(key,{cache:'reload'});
  if(!await verified(response,key))throw new Error('Asset revision mismatch: '+key);
  return [key,response];
 }));
 const cache=await caches.open(CACHE);
 await Promise.all(assets.map(([key,response])=>cache.put(key,response)));
 await self.skipWaiting();
})()));

async function removeOldAssetCaches(){
 for(const name of await caches.keys()){
  if(name===CACHE)continue;
  if(name.startsWith(CACHE_PREFIX)){
   await caches.delete(name);
  }else if(/^lmn-(?:preview-)?v[^:]+-web-[a-f0-9]{12}$/.test(name)){
   // Older cache names shared the origin. Only delete a cache owned by this site path.
   const requests=await (await caches.open(name)).keys();
   const inScope=url=>url.startsWith(ROOT.href)||url.startsWith(PACKAGES.href);
   if(requests.length&&requests.some(request=>request.url.startsWith(ROOT.href))&&requests.every(request=>inScope(request.url))){
    await caches.delete(name);
   }
  }
 }
}
self.addEventListener('activate',event=>event.waitUntil(
 removeOldAssetCaches().catch(()=>{}).then(()=>self.clients.claim())
));
self.addEventListener('fetch',event=>{
 const request=event.request,url=new URL(request.url);
 if(request.method!=='GET'||url.origin!==ROOT.origin)return;
 const key=ASSET_URLS.get(url.pathname);
 if(!key)return;
 const online=fetch(request,{cache:'no-cache'}).then(async response=>{
  if(await verified(response,key))return response;
  if(request.mode==='navigate')self.registration.update().catch(()=>{});
  return null;
 }).catch(()=>null);
 // Register the write before answering the request, even if the tab closes during the fetch.
 if(!url.search||request.mode==='navigate'){
  event.waitUntil(online.then(response=>{
   if(!response?.ok||response.redirected)return;
   const copy=response.clone();
   return caches.open(CACHE).then(cache=>cache.put(key,copy));
  }).catch(()=>{}));
 }
 event.respondWith(online.then(async response=>{
  if(response?.ok)return response;
  return await caches.match(key,{cacheName:CACHE}).catch(()=>undefined)||response||Response.error();
 }));
});
`;

await writeFile(new URL('apps/web/sw.js',base),worker);
console.log('Generated '+paths.length+' web assets for '+APP_VERSION);
