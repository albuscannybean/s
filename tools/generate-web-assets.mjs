import {readdir,readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import path from 'node:path';
import {APP_VERSION} from '../packages/app-metadata.js';
const base=new URL('../',import.meta.url);
// Discover native ESM dependencies once at build time to remove the cold-start waterfall.
const modules=new Set();
async function dependencies(file){
 if(modules.has(file))return;modules.add(file);
 const source=await readFile(new URL(file,base),'utf8');
 for(const match of source.matchAll(/(?:from\s*|import\s*)['"]([^'"]+)['"]/g)){
  if(!match[1].startsWith('.'))continue;
  const target=path.posix.normalize(path.posix.join(path.posix.dirname(file),match[1]));
  if(target.endsWith('.js'))await dependencies(target);
 }
}
await dependencies('apps/web/app.js');
const htmlUrl=new URL('apps/web/index.html',base),original=await readFile(htmlUrl,'utf8');
const preload='<!-- modulepreload:start -->\n'+[...modules].filter(p=>p!=='apps/web/app.js').sort().map(p=>'<link rel="modulepreload" href="'+(p.startsWith('apps/web/')?'./'+p.slice(9):'../../'+p)+'">').join('\n')+'\n<!-- modulepreload:end -->';
await writeFile(htmlUrl,original.includes('<!-- modulepreload:start -->')?original.replace(/<!-- modulepreload:start -->[\s\S]*?<!-- modulepreload:end -->/,preload):original.replace('</head>',preload+'\n</head>'));
async function walk(relative){const entries=await readdir(new URL(relative,base),{withFileTypes:true}),files=[];for(const entry of entries){const p=relative+entry.name;if(entry.isDirectory())files.push(...await walk(p+'/'));else files.push(p)}return files}
const packages=(await walk('packages/')).filter(p=>/\.(js|css)$/.test(p)),appFiles=(await walk('apps/web/')).filter(p=>!p.endsWith('/sw.js')&&/\.(js|mjs|html|css|woff2|webmanifest)$/.test(p));
const assets=[...appFiles,...packages].sort(),hash=createHash('sha256');for(const file of assets){hash.update(file);hash.update(await readFile(new URL(file,base)))}
const paths=['./',...assets.map(p=>p.startsWith('apps/web/')?'./'+p.slice(9):'../../'+p)];
const worker=String.raw`// Generated by tools/generate-web-assets.mjs. Do not maintain parallel asset lists.
const CACHE='lmn-v${APP_VERSION}-web-${hash.digest('hex').slice(0,12)}';
const ASSETS=${JSON.stringify(paths,null,2)};
const ASSET_PATHS=new Set(ASSETS.map(asset=>new URL(asset,self.location.href).pathname));
self.addEventListener('install',event=>event.waitUntil(caches.open(CACHE).then(cache=>cache.addAll(ASSETS)).then(()=>self.skipWaiting())));
self.addEventListener('activate',event=>event.waitUntil(caches.keys().then(keys=>Promise.all(keys.filter(key=>key.startsWith('lmn-v')&&key!==CACHE).map(key=>caches.delete(key)))).then(()=>self.clients.claim())));
self.addEventListener('fetch',event=>{
 if(event.request.method!=='GET'||new URL(event.request.url).origin!==self.location.origin)return;
 const known=ASSET_PATHS.has(new URL(event.request.url).pathname);
 const fresh=()=>fetch(event.request).then(response=>{if(response.ok&&known){const copy=response.clone();caches.open(CACHE).then(cache=>cache.put(event.request,copy)).catch(()=>{});}return response});
 // The shell and modules share one release cache; activation swaps the complete set.
 event.respondWith((async()=>{const cache=await caches.open(CACHE),cached=known?await cache.match(event.request,{ignoreSearch:true}):null;if(cached)return cached;try{return await fresh()}catch{return Response.error()}})());
});
`;
await writeFile(new URL('apps/web/sw.js',base),worker);
console.log('Generated '+paths.length+' web assets for '+APP_VERSION);
