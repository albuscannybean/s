import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {mkdir} from 'node:fs/promises';
const require=createRequire(import.meta.url),{chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const browser=await chromium.launch({headless:true,...(process.env.LMN_BROWSER_EXECUTABLE?{executablePath:process.env.LMN_BROWSER_EXECUTABLE}:{})});
const context=await browser.newContext({viewport:{width:1320,height:900},serviceWorkers:'block'}),page=await context.newPage(),errors=[];
page.on('pageerror',error=>errors.push(error.message));
await mkdir('qa-output',{recursive:true});
try{
  await page.goto(process.env.LMN_QA_URL||'http://127.0.0.1:4174/apps/web/',{waitUntil:'networkidle'});
  await page.waitForFunction(()=>!!globalThis.lmnWorkspace);
  await page.locator('#learningTopic').fill('一致收敛为何要求统一的 N？');
  await page.locator('#learningStartForm button[type=submit]').click();
  await page.locator('#studyWorkbench').waitFor({state:'visible'});
  assert.equal(await page.evaluate(()=>lmnWorkspace.state.knowledge.length),0,'session must not silently create Knowledge');
  assert.equal(await page.locator('[data-study-action="hint"]').isDisabled(),true);
  await page.locator('#studyDraft').fill('我认为 N 的选取不应该依赖 x，暂时不知道怎么证明。');
  await page.waitForTimeout(450);
  await page.reload({waitUntil:'networkidle'});
  await page.waitForFunction(()=>!!globalThis.lmnWorkspace);
  await page.locator('#studySessionsHome .learning-recent-row').click();
  assert.match(await page.locator('#studyDraft').inputValue(),/选取不应该依赖 x/);
  await page.locator('[data-study-action="submit"]').click();
  assert.equal(await page.locator('[data-study-action="hint"]').isEnabled(),true);
  await page.locator('[data-study-action="hint"]').click();
  assert.match(await page.locator('#studyHints').innerText(),/量词顺序/);
  await page.locator('[data-study-action="copy-context"]').click();
  const packet=await page.locator('#studyContextJson').inputValue(),request=JSON.parse(packet);
  assert.equal(request.hintLevel,1);assert.equal(request.attempt,'我认为 N 的选取不应该依赖 x，暂时不知道怎么证明。');
  const invalid={format:'lmn-study-feedback/1',sessionId:'invalid',attemptId:request.attemptId,summary:'不完整',strengths:[],issues:['缺反例'],nextAction:'先选 x_n'};
  await page.locator('#studyFeedbackInput').fill(JSON.stringify(invalid));
  await page.locator('[data-study-action="preview-feedback"]').click();
  assert.match(await page.locator('#studyStatus').innerText(),/另一学习会话/);
  await page.locator('#studyFeedbackInput').fill(JSON.stringify({...invalid,sessionId:request.sessionId}));
  await page.locator('[data-study-action="preview-feedback"]').click();
  assert.equal(await page.locator('[data-study-action="accept-feedback"]').isEnabled(),true);
  await page.locator('[data-study-action="accept-feedback"]').click();
  assert.match(await page.locator('.study-record-feedback').last().innerText(),/缺反例/);
  await page.locator('[data-study-action="stage"][data-value="transfer"]').first().click();
  assert.match(await page.locator('#studyQuestion').innerText(),/迁移检验/);
  await page.locator('#studyDraft').fill('对于 x≤a，有 x^n≤a^n。只要 a^N<ε 即可。');
  await page.locator('[data-study-action="submit"]').click();
  await page.locator('[data-study-action="finish"]').click();
  assert.match(await page.locator('.study-finish-panel').innerText(),/下次复习/);
  await page.locator('#studyDraft').fill('逐点是 ∀x∃N，一致是 ∃N∀x；取 x_n=2^(-1/n)');
  await page.locator('[data-study-action="submit"]').click();
  await page.locator('[data-study-action="review"][data-value="yes"]').click();
  assert.equal(await page.evaluate(()=>lmnWorkspace.studyWorkbench.current().reviews.length),1);
  await page.locator('[data-study-action="home"]').click();
  await page.screenshot({path:'qa-output/study-home.png'});
  const archive=await page.evaluate(async()=>{const {exportStudyArchive}=await import('../../packages/learning/study-session.js');return exportStudyArchive(lmnWorkspace.studyWorkbench.sessions)});
  const parsed=JSON.parse(archive);assert.equal(parsed.sessions.length,1);assert.equal(parsed.sessions[0].feedback.length,1);
  await page.locator('#studySessionsImport').setInputFiles({name:'study-archive.json',mimeType:'application/json',buffer:Buffer.from(archive)});
  await page.locator('#studyArchiveCommit').click();
  assert.match(await page.locator('#studyArchivePreview').innerText(),/导入完成/);
  await page.locator('#studySessionsHome .learning-recent-row').first().click();
  await page.screenshot({path:'qa-output/study-workbench.png'});
  for(const width of [390,768,1320]){await page.setViewportSize({width,height:850});assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),`overflow at ${width}`)}
  assert.deepEqual(errors,[]);
  console.log('Study workbench browser QA passed:',{sessions:parsed.sessions.length,attempts:parsed.sessions[0].attempts.length,feedback:parsed.sessions[0].feedback.length,reviews:parsed.sessions[0].reviews.length});
}finally{await browser.close()}
